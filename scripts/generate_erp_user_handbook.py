def build_html() -> str:
    manifest = json.loads(MANIFEST.read_text(encoding="utf-8"))
    existing = {item["slug"] for item in manifest}
    missing = [page[1] for page in PAGES if page[1] not in existing]
    if missing:
        raise RuntimeError(f"Missing screenshots in manifest: {missing}")

    parts = ["<!doctype html><html lang='fa' dir='rtl'><head><meta charset='utf-8'>",
             "<title>راهنمای جامع Hadron ERP System</title>", f"<style>{CSS}</style>", "</head><body>", cover(), intro_pages()]
    current = None
    for page in PAGES:
        workspace = page[0]
        if workspace != current:
            parts.append(section_page(workspace))
            current = workspace
        parts.append(screenshot_page(page))
        parts.append(field_page(page[1], page[2]))
    parts.append(appendix_pages())
    parts.append("</body></html>")
    return "".join(parts)


def main() -> None:
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    TMP_DIR.mkdir(parents=True, exist_ok=True)
    HTML_OUT.write_text(build_html(), encoding="utf-8")
    print(HTML_OUT)


if __name__ == "__main__":
    main()
